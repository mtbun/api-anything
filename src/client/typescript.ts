import type { JsonSchema } from "../schema/infer.ts";
import { pascal, typesOf, type ClientModel, type ClientOperation } from "./model.ts";

// Renders a single-file TypeScript client that uses the global fetch.

export function renderTypeScript(model: ClientModel): string {
  const types: string[] = [];
  const methods: string[] = [];

  for (const op of model.operations) {
    const base = pascal(op.name);
    const params = [...op.pathParams, ...op.queryParams];
    if (params.length > 0) {
      const fields = params.map((p) => `  ${prop(p.name)}${p.required ? "" : "?"}: ${tsType(p.schema)};`);
      types.push(`export interface ${base}Params {\n${fields.join("\n")}\n}`);
    }
    if (op.body) types.push(`export type ${base}Body = ${tsType(op.body)};`);
    types.push(`export type ${base}Response = ${op.response ? tsType(op.response) : "unknown"};`);
    methods.push(renderMethod(op, base, params.length > 0));
  }

  return `// Generated by api-anything from "${model.title}". Do not edit by hand;
// regenerate with: api-anything client <openapi.json> --lang ts
// Schemas were inferred from recorded traffic and cover only what was observed.

export interface ClientOptions {
  baseUrl?: string;
  /** Session headers (cookie, authorization, CSRF) sent with every request. */
  headers?: Record<string, string>;
  /** Credential query parameters, e.g. an API key the app sends in URLs. */
  query?: Record<string, string>;
  fetch?: typeof fetch;
}

export class ApiError extends Error {
  constructor(public readonly status: number, public readonly body: string, url: string) {
    super(\`HTTP \${status} from \${url}\`);
    this.name = "ApiError";
  }
}

${types.join("\n\n")}

export class ApiClient {
  private readonly baseUrl: string | undefined;
  private readonly headers: Record<string, string>;
  private readonly query: Record<string, string>;
  private readonly fetchImpl: typeof fetch;

  constructor(options: ClientOptions = {}) {
    this.baseUrl = options.baseUrl?.replace(/\\/$/, "");
    this.headers = options.headers ?? {};
    this.query = options.query ?? {};
    this.fetchImpl = options.fetch ?? fetch;
  }

  /**
   * Creates a client from a session file written by \`api-anything session\` or \`refresh\`.
   * The session is the one recorded for the app's own server, also when baseUrl points elsewhere.
   */
  static async fromSessionFile(path = ".api-anything/session.json", options: ClientOptions = {}): Promise<ApiClient> {
    const { readFile } = await import("node:fs/promises");
    const session = JSON.parse(await readFile(path, "utf8")) as {
      origins?: Record<string, Record<string, string>>;
      query?: Record<string, Record<string, string>>;
    };
    const origin = new URL(${JSON.stringify(model.server)}).origin;
    return new ApiClient({ headers: session.origins?.[origin] ?? {}, query: session.query?.[origin] ?? {}, ...options });
  }

${methods.join("\n\n")}

  private async request(
    server: string,
    method: string,
    path: string,
    query: Record<string, unknown>,
    credentialQuery: string[],
    body?: { mediaType: string; value: unknown },
  ): Promise<unknown> {
    const url = new URL((this.baseUrl ?? server) + path);
    for (const [name, value] of Object.entries(query)) {
      if (value !== undefined && value !== null) url.searchParams.set(name, String(value));
    }
    for (const name of credentialQuery) {
      const value = this.query[name];
      if (value !== undefined && !url.searchParams.has(name)) url.searchParams.set(name, value);
    }
    const headers: Record<string, string> = { accept: "application/json, */*", ...this.headers };
    let payload: string | undefined;
    if (body) {
      headers["content-type"] = body.mediaType;
      payload = typeof body.value === "string" ? body.value : JSON.stringify(body.value);
    }
    const response = await this.fetchImpl(url, { method, headers, body: payload, redirect: "manual" });
    const text = await response.text();
    if (!response.ok) throw new ApiError(response.status, text, url.href);
    const type = response.headers.get("content-type") ?? "";
    if (text === "") return undefined;
    return type.includes("json") ? JSON.parse(text) : text;
  }
}
`;
}

function renderMethod(op: ClientOperation, base: string, hasParams: boolean): string {
  const args: string[] = [];
  if (hasParams) {
    const allOptional = [...op.pathParams, ...op.queryParams].every((p) => !p.required);
    args.push(`params: ${base}Params${allOptional ? " = {}" : ""}`);
  }
  if (op.body) args.push(`body: ${base}Body`);

  let path = JSON.stringify(op.path);
  if (op.pathParams.length > 0) {
    path = "`" + op.path.replace(/\{([^{}]+)\}/g, (_, name: string) => `\${encodeURIComponent(String(params[${JSON.stringify(name)}]))}`) + "`";
  }
  const query = op.queryParams
    .map((p) => {
      const value = `params[${JSON.stringify(p.name)}]`;
      return `      ${JSON.stringify(p.name)}: ${p.default === undefined ? value : `${value} ?? ${JSON.stringify(p.default)}`},`;
    })
    .join("\n");
  const body = op.body ? `, { mediaType: ${JSON.stringify(op.bodyMediaType ?? "application/json")}, value: body }` : "";

  return `  /** ${op.summary}${op.writes ? " (changes data)" : ""} */
  async ${op.name}(${args.join(", ")}): Promise<${base}Response> {
    return (await this.request(
      ${JSON.stringify(op.server)},
      ${JSON.stringify(op.method)},
      ${path},
      {${query ? `\n${query}\n    ` : ""}},
      ${JSON.stringify(op.credentialQuery)}${body},
    )) as ${base}Response;
  }`;
}

export function tsType(schema: JsonSchema): string {
  const types = typesOf(schema);
  if (types.length === 0) return "unknown";
  const rendered = types.map((type) => {
    switch (type) {
      case "string":
        return "string";
      case "integer":
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array":
        return schema.items ? `Array<${tsType(schema.items)}>` : "unknown[]";
      case "object": {
        if (!schema.properties) return "Record<string, unknown>";
        const required = new Set(schema.required ?? []);
        const fields = Object.entries(schema.properties).map(
          ([key, child]) => `${prop(key)}${required.has(key) ? "" : "?"}: ${tsType(child)}`,
        );
        return `{ ${fields.join("; ")} }`;
      }
      default:
        return "unknown";
    }
  });
  return rendered.length === 1 ? rendered[0]! : rendered.join(" | ");
}

function prop(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}
