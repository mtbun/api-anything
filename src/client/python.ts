import type { JsonSchema } from "../schema/infer.ts";
import { pascal, typesOf, type ClientModel, type ClientOperation, type ClientParam } from "./model.ts";

// Renders a single-file Python client that uses only the standard library
// (urllib, json) and runs on Python 3.9+.

const KEYWORDS = new Set([
  "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue", "def", "del",
  "elif", "else", "except", "finally", "for", "from", "global", "if", "import", "in", "is", "lambda", "nonlocal",
  "not", "or", "pass", "raise", "return", "try", "while", "with", "yield", "self", "body", "params",
]);

export function renderPython(model: ClientModel): string {
  const typeDefs: string[] = [];
  const methods: string[] = [];

  for (const op of model.operations) {
    const base = pascal(op.name);
    const bodyType = op.body ? pyType(op.body, `${base}Body`, typeDefs) : undefined;
    const responseType = op.response ? pyType(op.response, `${base}Response`, typeDefs) : "Any";
    methods.push(renderMethod(op, bodyType, responseType));
  }

  return `# Generated by api-anything from ${JSON.stringify(model.title)}. Do not edit by hand;
# regenerate with: api-anything client <openapi.json> --lang py
# Schemas were inferred from recorded traffic and cover only what was observed.
from __future__ import annotations

import json
import urllib.error
import urllib.parse
import urllib.request
from typing import Any, Dict, List, Optional, Union

try:
    from typing import TypedDict
except ImportError:  # pragma: no cover
    from typing_extensions import TypedDict

DEFAULT_SERVER = ${JSON.stringify(model.server)}


class ApiError(Exception):
    def __init__(self, status: int, body: str, url: str) -> None:
        super().__init__(f"HTTP {status} from {url}")
        self.status = status
        self.body = body


${typeDefs.join("\n\n")}${typeDefs.length > 0 ? "\n\n\n" : ""}class ApiClient:
    def __init__(
        self,
        base_url: Optional[str] = None,
        headers: Optional[Dict[str, str]] = None,
        query: Optional[Dict[str, str]] = None,
        timeout: float = 30.0,
    ) -> None:
        """headers: session headers (cookie, authorization, CSRF) sent with every request.
        query: credential query parameters, e.g. an API key the app sends in URLs."""
        self.base_url = base_url.rstrip("/") if base_url else None
        self.headers = dict(headers or {})
        self.query = dict(query or {})
        self.timeout = timeout

    @classmethod
    def from_session_file(cls, path: str = ".api-anything/session.json", base_url: Optional[str] = None) -> "ApiClient":
        """Creates a client from a session file written by \`api-anything session\` or \`refresh\`.
        The session is the one recorded for the app's own server, also when base_url points elsewhere."""
        with open(path, encoding="utf-8") as f:
            session = json.load(f)
        parsed = urllib.parse.urlsplit(DEFAULT_SERVER)
        origin = f"{parsed.scheme}://{parsed.netloc}"
        return cls(
            base_url=base_url,
            headers=(session.get("origins") or {}).get(origin, {}),
            query=(session.get("query") or {}).get(origin, {}),
        )

${methods.join("\n\n")}

    def _request(
        self,
        server: str,
        method: str,
        path: str,
        query: Dict[str, Any],
        credential_query: List[str],
        body: Any = None,
        media_type: Optional[str] = None,
    ) -> Any:
        pairs = [(k, str(v).lower() if isinstance(v, bool) else str(v)) for k, v in query.items() if v is not None]
        pairs += [(k, self.query[k]) for k in credential_query if k in self.query and k not in query]
        url = (self.base_url or server) + path + ("?" + urllib.parse.urlencode(pairs) if pairs else "")
        headers = {"accept": "application/json, */*", **self.headers}
        data = None
        if media_type is not None:
            headers["content-type"] = media_type
            data = (body if isinstance(body, str) else json.dumps(body)).encode("utf-8")
        request = urllib.request.Request(url, data=data, headers=headers, method=method)
        try:
            with urllib.request.urlopen(request, timeout=self.timeout) as response:
                text = response.read().decode("utf-8")
                content_type = response.headers.get("content-type", "")
        except urllib.error.HTTPError as error:
            raise ApiError(error.code, error.read().decode("utf-8", "replace"), url) from None
        if text == "":
            return None
        return json.loads(text) if "json" in content_type else text
`;
}

function renderMethod(op: ClientOperation, bodyType: string | undefined, responseType: string): string {
  const required = [...op.pathParams, ...op.queryParams].filter((p) => p.required);
  const optional = op.queryParams.filter((p) => !p.required);
  const args = ["self"];
  for (const p of required) args.push(`${ident(p.name)}: ${pyType(p.schema, "", [])}`);
  if (bodyType) args.push(`body: ${bodyType}`);
  for (const p of optional) {
    const value = p.default === undefined ? "None" : typeof p.default === "boolean" ? (p.default ? "True" : "False") : JSON.stringify(p.default);
    args.push(`${ident(p.name)}: Optional[${pyType(p.schema, "", [])}] = ${value}`);
  }

  const path = op.pathParams.length === 0
    ? JSON.stringify(op.path)
    : `${JSON.stringify(op.path.replace(/\{([^{}]+)\}/g, (_, name: string) => `{${ident(name)}}`))}.format(${op.pathParams
        .map((p) => `${ident(p.name)}=urllib.parse.quote(str(${ident(p.name)}), safe="")`)
        .join(", ")})`;
  const query = `{${op.queryParams.map((p: ClientParam) => `${JSON.stringify(p.name)}: ${ident(p.name)}`).join(", ")}}`;
  const body = bodyType ? `, body, ${JSON.stringify(op.bodyMediaType ?? "application/json")}` : "";

  return `    def ${snake(op.name)}(${args.join(", ")}) -> ${responseType}:
        """${op.summary}${op.writes ? " (changes data)" : ""}"""
        return self._request(${JSON.stringify(op.server)}, ${JSON.stringify(op.method)}, ${path}, ${query}, ${JSON.stringify(op.credentialQuery)}${body})`;
}

// Object schemas become functional TypedDicts (keys may not be valid Python
// identifiers); nested ones are defined first so every name exists when used.
export function pyType(schema: JsonSchema, name: string, defs: string[]): string {
  const types = typesOf(schema);
  if (types.length === 0) return "Any";
  const nonNull = types.filter((t) => t !== "null");
  const rendered = nonNull.map((type) => {
    switch (type) {
      case "string":
        return "str";
      case "integer":
        return "int";
      case "number":
        return "float";
      case "boolean":
        return "bool";
      case "array":
        return schema.items ? `List[${pyType(schema.items, `${name}Item`, defs)}]` : "List[Any]";
      case "object": {
        if (!schema.properties || !name) return "Dict[str, Any]";
        const fields = Object.entries(schema.properties).map(
          ([key, child]) => `${JSON.stringify(key)}: ${pyType(child, `${name}${pascal(key)}`, defs)}`,
        );
        defs.push(`${name} = TypedDict(${JSON.stringify(name)}, {${fields.join(", ")}}, total=False)`);
        return name;
      }
      default:
        return "Any";
    }
  });
  let result = rendered.length === 0 ? "None" : rendered.length === 1 ? rendered[0]! : `Union[${rendered.join(", ")}]`;
  if (types.includes("null") && rendered.length > 0) result = `Optional[${result}]`;
  return result;
}

function snake(name: string): string {
  const s = name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
  return ident(s);
}

function ident(name: string): string {
  let id = name.replace(/[^A-Za-z0-9_]/g, "_").replace(/^(\d)/, "_$1");
  if (/[A-Z]/.test(id) && !id.includes("_")) id = id.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
  return KEYWORDS.has(id) ? `${id}_` : id;
}
