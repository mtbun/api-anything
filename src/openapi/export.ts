import { STATUS_CODES } from "node:http";
import type { Endpoint } from "../endpoints/group.ts";
import { isIdentifierSegment, singular } from "../endpoints/normalize.ts";
import type { JsonSchema } from "../schema/infer.ts";

// Builds an OpenAPI 3.1 document from discovered endpoints. OpenAPI 3.1 uses
// JSON Schema 2020-12, so inferred schemas are embedded as they are.

export interface OpenApiOptions {
  title?: string;
  version?: string;
  description?: string;
}

export interface OpenApiDocument {
  openapi: "3.1.0";
  info: { title: string; version: string; description?: string };
  servers: { url: string }[];
  paths: Record<string, Record<string, OpenApiOperation>>;
}

export interface OpenApiOperation {
  operationId: string;
  summary: string;
  servers?: { url: string }[];
  parameters?: OpenApiParameter[];
  requestBody?: { required: boolean; content: Record<string, { schema: JsonSchema }> };
  responses: Record<string, OpenApiResponse>;
  "x-api-anything": { observedCalls: number; examplePaths: string[] };
}

export interface OpenApiParameter {
  name: string;
  in: "path" | "query";
  required: boolean;
  schema: JsonSchema;
}

export interface OpenApiResponse {
  description: string;
  content?: Record<string, { schema: JsonSchema }>;
}

export function toOpenApi(endpoints: Endpoint[], options: OpenApiOptions = {}): OpenApiDocument {
  const origins = [...new Set(endpoints.map((e) => e.origin))];
  const primary = mostCommonOrigin(endpoints) ?? origins[0];
  const operationIds = uniqueOperationIds(endpoints);

  const paths: OpenApiDocument["paths"] = {};
  endpoints.forEach((endpoint, i) => {
    const operation = toOperation(endpoint, operationIds[i]!);
    if (endpoint.origin !== primary) operation.servers = [{ url: endpoint.origin }];
    const pathItem = (paths[endpoint.pathTemplate] ??= {});
    pathItem[endpoint.method.toLowerCase()] = operation;
  });

  const info: OpenApiDocument["info"] = {
    title: options.title ?? defaultTitle(primary),
    version: options.version ?? "0.1.0",
  };
  info.description =
    options.description ??
    "Generated by api-anything from a recorded browser session. Schemas are inferred from observed traffic and cover only what was seen.";

  return { openapi: "3.1.0", info, servers: primary ? [{ url: primary }] : [], paths };
}

function toOperation(endpoint: Endpoint, operationId: string): OpenApiOperation {
  const parameters = [...pathParameters(endpoint), ...queryParameters(endpoint)];
  const operation: OpenApiOperation = {
    operationId,
    summary: `${endpoint.method} ${endpoint.pathTemplate}`,
    responses: {},
    "x-api-anything": { observedCalls: endpoint.callCount, examplePaths: endpoint.examplePaths },
  };
  if (parameters.length > 0) operation.parameters = parameters;

  if (endpoint.requestBody) {
    operation.requestBody = {
      required: true,
      content: { [mediaType(endpoint.requestMimeType)]: { schema: endpoint.requestBody } },
    };
  }

  for (const response of endpoint.responses) {
    const entry: OpenApiResponse = { description: STATUS_CODES[response.status] ?? `Status ${response.status}` };
    if (response.body) entry.content = { [mediaType(response.mimeType)]: { schema: response.body } };
    operation.responses[String(response.status)] = entry;
  }
  return operation;
}

function pathParameters(endpoint: Endpoint): OpenApiParameter[] {
  const templateSegments = endpoint.pathTemplate.split("/");
  const samples = endpoint.examplePaths.map((p) => p.split("?")[0]!.split("/"));
  return templateSegments.flatMap((segment, index) => {
    const match = /^\{(.+)\}$/.exec(segment);
    if (!match) return [];
    const values = samples.map((s) => decodeURIComponent(s[index] ?? "")).filter(Boolean);
    return [{ name: match[1]!, in: "path" as const, required: true, schema: pathValueSchema(values) }];
  });
}

function pathValueSchema(values: string[]): JsonSchema {
  const examples = [...new Set(values)].slice(0, 3);
  if (values.length > 0 && values.every((v) => /^\d+$/.test(v))) {
    return { type: "integer", examples: examples.map(Number) };
  }
  if (values.length > 0 && values.every((v) => /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(v))) {
    return { type: "string", format: "uuid", examples };
  }
  if (values.length > 0 && values.every((v) => /^\d{4}-\d{2}-\d{2}$/.test(v))) {
    return { type: "string", format: "date", examples };
  }
  return examples.length > 0 ? { type: "string", examples } : { type: "string" };
}

function queryParameters(endpoint: Endpoint): OpenApiParameter[] {
  return endpoint.queryParameters.map((p) => ({
    name: p.name,
    in: "query" as const,
    required: p.required,
    schema: p.examples.length > 0 && p.examples.every((v) => /^\d+$/.test(v))
      ? { type: "integer", examples: p.examples.map(Number) }
      : { type: "string", examples: p.examples },
  }));
}

function mediaType(mime: string | undefined): string {
  return mime?.split(";")[0]?.trim() || "application/json";
}

function mostCommonOrigin(endpoints: Endpoint[]): string | undefined {
  const counts = new Map<string, number>();
  for (const e of endpoints) counts.set(e.origin, (counts.get(e.origin) ?? 0) + e.callCount);
  return [...counts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))[0]?.[0];
}

function defaultTitle(origin: string | undefined): string {
  return origin ? `${new URL(origin).hostname} API` : "Discovered API";
}

// operationIds follow REST conventions so that generated clients and MCP
// tools read naturally: listOrders, getOrder, createOrder, listCustomerInvoices.
export function operationIdFor(method: string, pathTemplate: string): string {
  const segments = pathTemplate.split("/").filter(Boolean);
  const endsWithParam = segments.length > 0 && segments[segments.length - 1]!.startsWith("{");
  const literals = segments.filter(
    (s) => !s.startsWith("{") && !/^api$/i.test(s) && !/^v\d+(\.\d+)?$/i.test(s) && !isIdentifierSegment(s),
  );

  const verb = verbFor(method.toUpperCase(), endsWithParam);
  const words = literals.map((word, i) => {
    const isLast = i === literals.length - 1;
    const keepPlural = isLast && verb === "list";
    return pascal(keepPlural ? word : singular(word));
  });
  return verb + (words.join("") || "Root");
}

function verbFor(method: string, endsWithParam: boolean): string {
  switch (method) {
    case "GET":
      return endsWithParam ? "get" : "list";
    case "POST":
      return "create";
    case "PUT":
      return "replace";
    case "PATCH":
      return "update";
    case "DELETE":
      return "delete";
    default:
      return method.toLowerCase();
  }
}

function uniqueOperationIds(endpoints: Endpoint[]): string[] {
  const seen = new Map<string, number>();
  return endpoints.map((e) => {
    const base = operationIdFor(e.method, e.pathTemplate);
    const count = (seen.get(base) ?? 0) + 1;
    seen.set(base, count);
    return count === 1 ? base : `${base}${count}`;
  });
}

function pascal(word: string): string {
  return word
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
}

